import { USE_MOCK } from './client';
import { MOCK_NOW } from './mock/seed';

/**
 * «دلوقتي» الموحّد للحسابات الزمنية في الواجهات (أيام معروضة،
 * عدّادات تنازلية، تأخير الأعمال المجدولة…).
 *
 * في وضع الموك بيرجع لحظة الـseed المجمّدة — عشان كل الحسابات تبقى
 * متسقة مع الداتا المولّدة والسكرينشوتس ثابتة. مع الباك اند الحقيقي
 * بيرجع `Date.now()` عادي. **الصفحات تستخدم دي، مش `MOCK_NOW`.**
 */
export function nowMs(): number {
  return USE_MOCK ? MOCK_NOW : Date.now();
}
